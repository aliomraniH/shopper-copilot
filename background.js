// Background Service Worker for Shopper Copilot

console.log('Shopper Copilot: Background service worker started');

// Extension installation handler
chrome.runtime.onInstalled.addListener((details) => {
  console.log('Shopper Copilot: Extension installed', details);

  if (details.reason === 'install') {
    // First time installation
    chrome.storage.local.set({
      integrations: {
        whatsapp: false,
        telegram: false,
        messenger: false
      },
      settings: {
        autoSummarize: false,
        notificationsEnabled: true,
        theme: 'light'
      },
      friends: []
    });

    // Open welcome page (optional)
    console.log('Shopper Copilot: First time setup complete');
  }
});

// Handle messages from content scripts and popup
chrome.runtime.onMessage.addListener((request, sender, sendResponse) => {
  console.log('Background received message:', request);

  switch (request.action) {
    case 'analyzePage':
      analyzePage(request.data)
        .then(result => sendResponse({ success: true, data: result }))
        .catch(error => sendResponse({ success: false, error: error.message }));
      return true; // Keep channel open for async response

    case 'sendToMessenger':
      sendToMessagingApp(request.platform, request.message, request.recipient)
        .then(result => sendResponse({ success: true, data: result }))
        .catch(error => sendResponse({ success: false, error: error.message }));
      return true;

    case 'getIntegrationStatus':
      chrome.storage.local.get(['integrations'], (result) => {
        sendResponse({ success: true, data: result.integrations || {} });
      });
      return true;

    case 'updateIntegration':
      updateIntegration(request.platform, request.status)
        .then(result => sendResponse({ success: true, data: result }))
        .catch(error => sendResponse({ success: false, error: error.message }));
      return true;

    default:
      sendResponse({ success: false, error: 'Unknown action' });
  }
});

