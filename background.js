// Send message to messaging apps
async function sendToMessagingApp(platform, message, recipient) {
  console.log(`Sending to ${platform}:`, message, recipient);

  // Get integration credentials from storage
  const integrations = await chrome.storage.local.get(['integrations']);

  if (!integrations.integrations || !integrations.integrations[platform]) {
    throw new Error(`${platform} is not connected. Please configure integration first.`);
  }

  // In production, this would call the respective messaging API
  // WhatsApp Business API: https://developers.facebook.com/docs/whatsapp
  // Telegram Bot API: https://core.telegram.org/bots/api
  // Messenger API: https://developers.facebook.com/docs/messenger-platform

  return new Promise((resolve) => {
    setTimeout(() => {
      resolve({
        messageId: 'mock_' + Date.now(),
        platform: platform,
        sent: true,
        timestamp: new Date().toISOString()
      });
    }, 500);
  });
}

// Update integration status
async function updateIntegration(platform, status) {
  return new Promise((resolve, reject) => {
    chrome.storage.local.get(['integrations'], (result) => {
      const integrations = result.integrations || {};
      integrations[platform] = status;

      chrome.storage.local.set({ integrations }, () => {
        if (chrome.runtime.lastError) {
          reject(new Error(chrome.runtime.lastError.message));
        } else {
          resolve({ platform, status });
        }
      });
    });
  });
}

// Context menu setup (optional - for right-click actions)
chrome.runtime.onInstalled.addListener(() => {
  chrome.contextMenus.create({
    id: 'summarizePage',
    title: 'Summarize this page',
    contexts: ['page']
  });

  chrome.contextMenus.create({
    id: 'shareWithFriend',
    title: 'Share with friend',
    contexts: ['page', 'selection']
  });
});

// Handle context menu clicks
chrome.contextMenus.onClicked.addListener((info, tab) => {
  console.log('Context menu clicked:', info.menuItemId);

  switch (info.menuItemId) {
    case 'summarizePage':
      chrome.tabs.sendMessage(tab.id, {
        action: 'summarizePage'
      });
      break;

    case 'shareWithFriend':
      chrome.tabs.sendMessage(tab.id, {
        action: 'toggleWidget',
        tab: 'friends'
      });
      break;
  }
});

// Listen for tab updates (optional - for auto-summarization)
chrome.tabs.onUpdated.addListener((tabId, changeInfo, tab) => {
  if (changeInfo.status === 'complete' && tab.url) {
    console.log('Tab updated:', tab.url);

    // Check if auto-summarize is enabled
    chrome.storage.local.get(['settings'], (result) => {
      if (result.settings && result.settings.autoSummarize) {
        // Trigger auto-summarization
        chrome.tabs.sendMessage(tabId, {
          action: 'autoSummarize'
        });
      }
    });
  }
});

